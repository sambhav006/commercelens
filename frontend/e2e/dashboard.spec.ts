import { test, expect } from '@playwright/test';

test('five pages, active filters, exports, empty states and responsive layout',async({page,request})=>{
 const errors:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Business at a glance'})).toBeVisible();
 await expect(page.locator('.source-badge')).toHaveText('Synthetic demo data');
 await expect(page.locator('.kpi')).toHaveCount(6);
 await expect(page.locator('.recharts-surface').first()).toBeVisible();
 await page.screenshot({path:'../docs/screenshots/overview.png',fullPage:true});
 const nav=page.getByRole('navigation');
 await nav.getByRole('button',{name:'Products & Regions'}).click();
 await expect(page.getByRole('heading',{name:'Category rankings'})).toBeVisible();
 await page.getByRole('combobox',{name:'Category',exact:true}).selectOption('health_beauty');
 await page.getByRole('combobox',{name:'Customer state',exact:true}).selectOption('SP');
 await page.getByRole('button',{name:'Apply filters'}).click();
 await expect(page.locator('.active-filters')).toContainText('Health Beauty');
 await expect(page.getByRole('heading',{name:'Category rankings'})).toBeVisible();
 const link=page.getByRole('link',{name:'Export categories CSV'});
 const exported=await request.get((await link.getAttribute('href'))!);
 expect(exported.status()).toBe(200);
 expect(await exported.text()).toContain('health_beauty');
 await page.getByRole('button',{name:'Sales (BRL)',exact:true}).first().click();
 await nav.getByRole('button',{name:'Customers',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Monthly cohort retention'})).toBeVisible();
 await expect(page.getByText('Category and state filters do not apply here.',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 await expect(page.locator('.active-filters')).toContainText('All categories');
 await expect(page.locator('.heatmap')).toBeVisible();
 await page.screenshot({path:'../docs/screenshots/customers.png',fullPage:true});
 await nav.getByRole('button',{name:'Delivery & Reviews'}).click();
 await expect(page.getByRole('heading',{name:'Reviews by delivery outcome'})).toBeVisible();
 await page.screenshot({path:'../docs/screenshots/delivery.png',fullPage:true});
 await nav.getByRole('button',{name:'Data Quality',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Metric dictionary'})).toBeVisible();
 await page.locator('.metric summary').first().click();
 await expect(page.locator('.metric').first()).toContainText('Freight');
 await page.screenshot({path:'../docs/screenshots/methodology.png',fullPage:true});
 await nav.getByRole('button',{name:'Executive Overview'}).click();
 await page.getByLabel('Start date').fill('2028-01-01');
 await page.getByLabel('End date').fill('2028-01-31');
 await page.getByRole('button',{name:'Apply filters'}).click();
 await expect(page.locator('.kpi').first()).toContainText('Unavailable');
 await expect(page.getByText('No observations available for this selection.')).toBeVisible();
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 await expect(page.locator('.kpi').first()).not.toContainText('Unavailable');
 await page.setViewportSize({width:820,height:1180});
 await page.screenshot({path:'../docs/screenshots/tablet.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 expect(errors).toEqual([]);
});

test('API error is actionable and retry recovers',async({page})=>{
 await page.route('**/api/dashboard*',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Test API unavailable'})}));
 await page.goto('/');
 await expect(page.getByRole('alert')).toContainText('Test API unavailable');
 await page.unroute('**/api/dashboard*');
 await page.getByRole('button',{name:'Retry',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Business at a glance'})).toBeVisible();
});
